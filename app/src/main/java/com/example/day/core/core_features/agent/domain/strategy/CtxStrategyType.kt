package com.example.day.core.core_features.agent.domain.strategy

enum class CtxStrategyType {
    /**
     * Стратегия скользящего окна - ограничивает количество сообщений.
     */
    SLIDING_WINDOW,

    /**
     * Стратегия саммаризации - сжимает старые сообщения.
     */
    SUMMARIZATION,

    /**
     * Полный контекст - сохраняет все сообщения без ограничений.
     */
    FULL_CONTEXT,

    /**
     * Стратегия Sticky Facts - хранит факты (key-value) + окно последних сообщений.
     * Факты обновляются после каждого ответа LLM.
     */
    STICKY_FACTS,

    /**
     * Стратегия ветвления - позволяет создавать независимые ветки диалога.
     * Каждая ветка хранит свою историю сообщений, можно переключаться между ветками.
     */
    BRANCHING,
    EMPTY
}